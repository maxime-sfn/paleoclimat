import csv
import numpy as np
import matplotlib.pyplot as plt

def lisser_et_afficher(fichier, y, titre):
    # Lecture du fichier CSV
    with open(fichier, newline='', encoding='utf-8') as fichier_csv:
        lecteur = csv.reader(fichier_csv)
        lignes = list(lecteur)
    colonnes = list(map(list, zip(*lignes)))
    for i in range(len(colonnes)):
        del colonnes[i][0]

    # Choix de la colonne à lisser (colonne 1)
    Colonne_a_moyenner = np.array(colonnes[1])

    # Initialiser la colonne lissée
    Colonne_moyenne = np.zeros(len(Colonne_a_moyenner))

    for i in range(len(Colonne_a_moyenner)):
        if i >= y:
            somme = 0
            for x in range(i - y, i):
                somme += float(Colonne_a_moyenner[x])
            Colonne_moyenne[i] = (1 / y) * somme
        else:
            Colonne_moyenne[i] = float(Colonne_a_moyenner[i])

    # Abscisses
    x = np.array(colonnes[0])

    '''
    # Affichage courbe lissée seule
    plt.figure(figsize=(18, 6))
    plt.plot(x, Colonne_moyenne, label='Moyenne mobile', color='blue')
    plt.xlabel("X (Colonne 0)")
    plt.ylabel("Moyenne (Colonne 1)")
    plt.title("Courbe lissée")
    plt.xticks(rotation=60)
    plt.grid(True)
    plt.legend()
    plt.tight_layout()
    plt.show()
    '''

    # Affichage comparaison valeurs originales vs lissées
    y_originale = np.array(Colonne_a_moyenner, dtype=float)
    y_moyenne = Colonne_moyenne

    plt.figure(figsize=(18, 6))
    plt.plot(x, y_originale, label='Valeurs originales', color='orange', linestyle='--')
    plt.plot(x, y_moyenne, label='Moyenne mobile', color='blue')
    plt.xlabel("X (Colonne 0)")
    plt.ylabel("Valeurs")
    plt.title("Comparaison Données/Données filtrées par une filtre moyenneur à " + str(y) + " années sur les données: " + titre)
    plt.xticks(rotation=60)
    plt.grid(True)
    plt.legend()
    plt.tight_layout()
    plt.xticks(ticks=range(0, len(x), 20), rotation=45)
    plt.show()

lisser_et_afficher("donnee.csv", 10, "Titre")
